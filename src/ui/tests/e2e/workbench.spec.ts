async function openPickedDocuments(page: Page, names: string[]): Promise<void> {
  const first = names[0]
  if (!first) throw new Error('至少选择一个文档')
  await page.getByTestId('menu-file').click()
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('menuitem', { name: '打开文件…', exact: true }).click()
  await (await chooser).setFiles(names.map((name) => ({
    name, mimeType: 'text/markdown', buffer: Buffer.from(`# ${name}\n\n[正文链接](#正文链接)\n\n正文内容。`),
  })))
  await expect(page.getByRole('tab')).toHaveCount(names.length)
  await expect(page.getByRole('tab', { name: first, exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('article h1')).toHaveText(first)
}

async function mockDocumentLocation(page: Page, name: string, directory: string, readError?: string): Promise<void> {
  // 只为浏览器桥接提供路径/读取结果；文档会话与界面仍走真实工作台流程。
  await page.evaluate(async ({ name, directory, readError }) => {
    const modulePath = '/src/core/ipc/mockBridge.ts'
    const { mockBridge } = await import(modulePath)
    const originalOpen = mockBridge.openDocument.bind(mockBridge)
    const originalMeta = mockBridge.readDocumentMeta.bind(mockBridge)
    mockBridge.openDocument = async (path: string) => ({
      ...await originalOpen(path === directory + name ? 'basic.md' : path),
      name, dir: directory.slice(0, -1), path: directory + name,
    })
    // Initial reads now verify metadata before and after bytes; both boundaries
    // must describe the same simulated file, as the real host does.
    mockBridge.readDocumentMeta = async (docId: string) => ({
      ...await originalMeta(docId), name, dir: directory.slice(0, -1), path: directory + name,
    })
    if (readError !== null) mockBridge.readDocument = async () => { throw { code: 'E_READ_FAILED', message: readError } }
  }, { name, directory, readError: readError ?? null })
}

