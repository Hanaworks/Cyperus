function replaceOnce(source, before, after, label) {
  if (source.split(before).length !== 2) throw Error(`Unexpected ${label}; review pinned upstream before trimming`)
  return source.replace(before, after)
}

function omitSection(source, start, end, label) {
  const first = source.indexOf(start)
  const last = source.indexOf(end, first + start.length)
  const next = source.indexOf(start, first + start.length)
  if (first < 0 || last < 0 || (next >= 0 && next < last)) throw Error(`Unexpected ${label}; review pinned upstream before trimming`)
  return source.slice(0, first) + source.slice(last)
}

function omitImports(source, ts, predicate) {
  const file = ts.createSourceFile('backend.ts', source, ts.ScriptTarget.Latest, true)
  const imports = file.statements.filter(node => ts.isImportDeclaration(node) && predicate(node.moduleSpecifier.text))
  for (const node of imports.reverse()) source = source.slice(0, node.getStart(file)) + source.slice(node.end)
  return source
}

function patchSharedProcess(source, ts) {
  if (source.includes(marker)) return source
  source = source.replace(/\r\n/g, '\n')
  source = omitSection(source, '\t\t// Tunnel\n', '\t\t// Web Content Extractor\n', 'shared tunnel services')
  source = omitSection(source, '\t\t// SSH Remote Agent Host\n', '\t\treturn new InstantiationService(services);', 'shared Agent Host services')
  source = omitSection(source, '\t\t// Tunnel\n', '\t\t// Web Content Extractor\n', 'shared tunnel channels')
  source = omitSection(source, '\t\t// Playwright\n', '\t\t// Local Git\n', 'shared Playwright channel')
  source = omitSection(source, '\t\t// SSH Remote Agent Host\n', '\n\t}\n\n\tprivate registerErrorHandler', 'shared Agent Host channels')
  source = replaceOnce(source, '\t\tthis.server.registerChannel(agentHostMcpOAuthMetadataChannelName, ProxyChannel.fromService(instantiationService.createInstance(AgentHostMcpOAuthMetadataService), this._store));', '\t\tregisterReaderDisabledChannels(this.server);', 'Agent Host OAuth channel')
  source = omitImports(source, ts, id => id.includes('/platform/agentHost/') || id.includes('/platform/tunnel/') || id.includes('/platform/remoteTunnel/') || id.includes('/platform/browserView/node/playwrightChannel') || id.includes('/platform/networkFilter/common/networkFilterService') || id.includes('/platform/remote/common/sharedProcessTunnelService') || id.includes('/platform/remote/common/remoteSocketFactoryService') || id.includes('/platform/remote/common/remoteAuthorityResolver') || id.includes('/platform/remote/node/nodeSocketFactory'))
  return `${marker}\nimport { registerReaderDisabledChannels } from './readerDisabledChannels.js';\n${source}`
}

