const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { resolveLocal, resolveLocalFile, readMarkdown, imageData, isWithin } = require('./security.cjs')

test('document decoding and local resource boundaries', async () => {
  const root = path.resolve(__dirname, '../../../artifacts/code-oss/security-test')
  await fs.mkdir(root, { recursive: true })
  await fs.mkdir(path.join(root, 'inside'), { recursive: true })
  const inside = path.join(root, 'inside')
  await fs.writeFile(path.join(inside, '中文.md'), '# 中文\n')
  await fs.writeFile(path.join(root, 'outside.md'), '# outside')
  await fs.writeFile(path.join(inside, 'utf16.md'), Buffer.concat([Buffer.from([255, 254]), Buffer.from('# UTF16 中文', 'utf16le')]))
  await fs.writeFile(path.join(inside, 'binary.md'), Buffer.from([0, 1, 2]))
  await fs.writeFile(path.join(inside, 'image.png'), Buffer.from([137, 80, 78, 71]))
  assert.equal((await readMarkdown(path.join(inside, '中文.md'))).text, '# 中文\n')
  assert.equal((await readMarkdown(path.join(inside, 'utf16.md'))).encoding, 'utf-16le')
  await assert.rejects(readMarkdown(path.join(inside, 'binary.md')))
  assert.equal(await resolveLocal(inside, '%E4%B8%AD%E6%96%87.md#标题'), path.join(inside, '中文.md'))
  for (const raw of ['../outside.md', '%2e%2e/outside.md', 'https://example.com/a.md', 'command:evil', 'file:///C:/a.md', '\\\\server\\share\\a.md', 'C:\\a.md', '%00.md', 'image.png:stream']) await assert.rejects(resolveLocal(inside, raw))
  assert.equal(isWithin(inside, `${inside}-other/file.md`), false)
  await fs.symlink(root, path.join(inside, 'outside-link'), 'junction').catch((error) => { if (error.code !== 'EEXIST') throw error })
  await assert.rejects(resolveLocal(inside, 'outside-link/outside.md'))
  assert.match(await imageData(inside, 'image.png'), /^data:image\/png;base64,/)
  await assert.rejects(imageData(inside, '中文.md'))
})

test('resolved Markdown paths retain literal percent and fragment characters when opened', async () => {
  const root = path.resolve(__dirname, '../../../artifacts/code-oss/link-path-test')
  const nested = path.join(root, '子目录')
  await fs.mkdir(nested, { recursive: true })
  const target = path.join(nested, '中文 #%20.md')
  await fs.writeFile(target, '# Link target\n')
  const resolved = await resolveLocal(root, '%E5%AD%90%E7%9B%AE%E5%BD%95/%E4%B8%AD%E6%96%87%20%23%2520.md#标题')
  assert.equal(resolved, target)
  assert.equal(await resolveLocalFile(root, resolved), target)
  assert.equal((await readMarkdown(await resolveLocalFile(root, resolved))).text, '# Link target\n')
})

test('filesystem link revalidation keeps directory and junction boundaries', async () => {
  const root = path.resolve(__dirname, '../../../artifacts/code-oss/link-boundary-test')
  const inside = path.join(root, 'inside')
  await fs.mkdir(inside, { recursive: true })
  await fs.writeFile(path.join(root, 'outside.md'), '# Outside\n')
  await fs.symlink(root, path.join(inside, 'outside-link'), process.platform === 'win32' ? 'junction' : 'dir').catch(error => { if (error.code !== 'EEXIST') throw error })
  for (const target of [path.join(root, 'outside.md'), path.join(inside, 'outside-link', 'outside.md'), inside, path.join(inside, 'missing.md')]) {
    await assert.rejects(resolveLocalFile(inside, target))
  }
})

test('filesystem link revalidation rejects Windows alternate data streams', { skip: process.platform !== 'win32' }, async () => {
  const root = path.resolve(__dirname, '../../../artifacts/code-oss/link-path-test')
  const file = path.join(root, 'stream-base.md')
  await fs.mkdir(root, { recursive: true })
  await fs.writeFile(file, '# Base\n')
  await fs.writeFile(`${file}:hidden.md`, '# Alternate stream\n')
  await assert.rejects(resolveLocalFile(root, `${file}:hidden.md`))
})
