// Source-run workbench trimming. This does not delete packaged code or shared
// extension API services, and must not be used as evidence of size/perf savings.
function generateServiceContribution(source, ts, label, { retainCalls = [], sideEffectImports = [] } = {}) {
  const file = ts.createSourceFile(label, source, ts.ScriptTarget.Latest, true)
  const serviceCalls = new Set(['registerSingleton', 'registerMainProcessRemoteService', 'registerSharedProcessRemoteService', ...retainCalls])
  const statements = file.statements.filter(node => ts.isExpressionStatement(node)
    && ts.isCallExpression(node.expression)
    && ts.isIdentifier(node.expression.expression)
    && serviceCalls.has(node.expression.expression.text))
  if (!statements.length) throw Error(`No service registrations found in ${label}`)
  const required = new Set()
  function collect(node) {
    if (ts.isIdentifier(node) && !(ts.isPropertyAccessExpression(node.parent) && node.parent.name === node)) required.add(node.text)
    ts.forEachChild(node, collect)
  }
  statements.forEach(collect)
  const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed })
  const imports = sideEffectImports.map(path => `import '${path}';`)
  for (const node of file.statements.filter(ts.isImportDeclaration)) {
    const clause = node.importClause
    if (!clause) continue
    const name = clause.name && required.has(clause.name.text) ? clause.name : undefined
    const bindings = clause.namedBindings
    let selected
    if (bindings && ts.isNamespaceImport(bindings) && required.has(bindings.name.text)) selected = bindings
    if (bindings && ts.isNamedImports(bindings)) {
      const elements = bindings.elements.filter(binding => required.has(binding.name.text))
      if (elements.length) selected = ts.factory.updateNamedImports(bindings, elements)
    }
    if (!name && !selected) continue
    if (name) required.delete(name.text)
    if (selected && ts.isNamespaceImport(selected)) required.delete(selected.name.text)
    if (selected && ts.isNamedImports(selected)) selected.elements.forEach(binding => required.delete(binding.name.text))
    const updated = ts.factory.updateImportDeclaration(node, node.modifiers,
      ts.factory.updateImportClause(clause, clause.isTypeOnly, name, selected), node.moduleSpecifier, node.attributes)
    imports.push(printer.printNode(ts.EmitHint.Unspecified, updated, file))
  }
  if (required.size) throw Error(`Review ${label}: service registrations depend on local declarations: ${[...required].join(', ')}`)
  const calls = statements.map(node => node.getText(file).replace(/InstantiationType\.Eager/g, 'InstantiationType.Delayed'))
  return `// Generated by Markdown Reader prepare-upstream. Shared services only; feature UI/startup contributions omitted.\n${imports.join('\n')}\n\n${calls.join('\n')}\n`
}

function patchEntryImports(source, replacements, label) {
  const lines = source.split('\n')
  for (const [original, replacement] of Object.entries(replacements)) {
    const before = `import '${original}';`
    const after = replacement ? `import '${replacement}';` : `// Markdown Reader omitted: ${before}`
    const candidates = new Set([before, after, `// Markdown Reader omitted: ${before}`])
    // Accept generated omissions from an earlier policy only as a complete line.
    if (replacement) candidates.add(`// Markdown Reader omitted: ${after}`)
    const indexes = lines.flatMap((line, index) => candidates.has(line.replace(/\r$/, '')) ? [index] : [])
    if (indexes.length !== 1) throw Error(`Unexpected import in ${label}: ${original}`)
    const index = indexes[0]
    lines[index] = after + (lines[index].endsWith('\r') ? '\r' : '')
  }
  return lines.join('\n')
}

