function patchAccountActions(source) {
  const replacements = [
    ["return storageService.getBoolean(AccountsActivityActionViewItem.ACCOUNTS_VISIBILITY_PREFERENCE_KEY, StorageScope.PROFILE, true);", 'return false; // Markdown Reader has no account entry.'],
    ["return [toAction({ id: 'toggleAccountsVisibility', label: localize('accounts', \"Accounts\"), checked: this.accountsVisibilityPreference, run: () => this.accountsVisibilityPreference = !this.accountsVisibilityPreference })];", 'return []; // Markdown Reader omits the account visibility toggle.'],
    ["toAction({ id: 'toggle.hideAccounts', label: localize('accounts', \"Accounts\"), checked: isAccountsActionVisible(storageService), run: () => setAccountsActionVisible(storageService, !isAccountsActionVisible(storageService)) }),", '// Markdown Reader omits the compact account visibility toggle.'],
  ]
  for (const [before, after] of replacements) {
    if (source.includes(after)) continue
    if (source.split(before).length !== 2) throw Error('Unexpected account actions; review upstream before patching')
    source = source.replace(before, after)
  }
  return source
}

const debugCommandsImport = "import { DEBUG_CONFIGURE_COMMAND_ID, DEBUG_CONFIGURE_LABEL } from './debugCommands.js';\n"
const commandServiceImport = "import { ICommandService } from '../../../../platform/commands/common/commands.js';\n"
const commandServiceParameter = '\t\t@ICommandService private readonly commandService: ICommandService,\n'
const debugServiceMarker = '// Markdown Reader omits prompts for the disabled debug commands.'

function patchDebugServiceSource(source, label, replacements) {
  if (source.startsWith(`${debugServiceMarker}\n`)) return source
  source = source.replace(/\r\n/g, '\n')
  for (const [before, after] of [[debugCommandsImport, ''], [commandServiceImport, ''], [commandServiceParameter, ''], ...replacements]) {
    if (source.split(before).length !== 2) throw Error(`Unexpected ${label}; review upstream before trimming debug commands`)
    source = source.replace(before, after)
  }
  return `${debugServiceMarker}\n${source}`
}

